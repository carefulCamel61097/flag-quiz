/**
 * Loads and caches the country dataset.
 *
 * Paths are resolved against document.baseURI rather than hard-coded from the
 * site root, so the site works both at a domain root and under a project path
 * like /flag-quiz/ on GitHub Pages.
 */

const url = (path) => new URL(path, document.baseURI).href;

/**
 * Which flags a quiz draws from.
 *
 * These are named for what they *are* - a slice of the countries ranked by
 * prominence - rather than Easy, Medium and Hard. Prominence is measured
 * (Wikipedia traffic blended with population, see scripts/build-flags.mjs);
 * difficulty is not measured yet, and labelling a set "Easy" would be the same
 * invented claim the mode cards used to make.
 *
 * The tiers are cumulative: the wider ones contain the narrower ones, so
 * moving up adds unfamiliar flags rather than swapping the familiar ones out.
 */
export const SCOPES = {
  known60: {
    id: 'known60',
    label: 'Best known',
    note: 'The countries that come up most. Nothing obscure.',
    match: (c) => c.sovereignty === 'un-member' && c.fameRank != null && c.fameRank <= 60,
  },
  known130: {
    id: 'known130',
    label: 'A few obscure',
    note: 'Adds countries you may have to stop and think about.',
    match: (c) => c.sovereignty === 'un-member' && c.fameRank != null && c.fameRank <= 130,
  },
  un: {
    id: 'un',
    label: 'Plenty obscure',
    note: 'Every UN member, down to Tuvalu, Nauru and Kiribati.',
    match: (c) => c.sovereignty === 'un-member',
  },
  all: {
    id: 'all',
    label: 'Obscure territories too',
    note: 'Adds Greenland, Hong Kong, Puerto Rico and the rest.',
    match: () => true,
  },
};

/** How many flags each selection covers, for labelling the choices. */
export async function scopeCounts() {
  const countries = await loadCountries();
  return Object.fromEntries(
    Object.values(SCOPES).map((s) => [s.id, countries.filter(s.match).length])
  );
}

export const DEFAULT_SCOPE = 'known130';

let cache = null;

export async function loadCountries() {
  if (!cache) {
    const res = await fetch(url('data/countries.json'));
    if (!res.ok) throw new Error(`Could not load country data (HTTP ${res.status})`);
    cache = await res.json();
  }
  return cache;
}

export async function countriesInScope(scopeId) {
  const scope = SCOPES[scopeId] ?? SCOPES[DEFAULT_SCOPE];
  return (await loadCountries()).filter(scope.match);
}

